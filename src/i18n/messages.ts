export const MESSAGES: Record<Locale, Messages> = { en, fr };

export function messagesFor(locale: Locale): Messages {
  return MESSAGES[locale];
}

/** Translates a project category ("Game", "Web app"...) when a translation exists. */
export function categoryLabel(locale: Locale, category: string): string {
  return MESSAGES[locale].categories[category] ?? category;
}
